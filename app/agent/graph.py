"""The LangGraph `StateGraph` (§B9.1), its SQLite checkpointer (§B9.2) and the Mermaid export.

`python -m app.agent.graph` writes docs/agent_graph.md.
"""
from __future__ import annotations

from contextlib import asynccontextmanager
from pathlib import Path

import aiosqlite
from langchain_core.messages import HumanMessage
from langgraph.checkpoint.serde.jsonplus import JsonPlusSerializer
from langgraph.checkpoint.sqlite.aio import AsyncSqliteSaver
from langgraph.graph import END, START, StateGraph

from app.agent.nodes import AgentNodes
from app.agent.state import CHECKPOINT_TYPES, AgentState

RECURSION_LIMIT = 40  # supersteps; the longest path (5 agent steps, one regeneration) needs 18


def build_graph(nodes: AgentNodes, checkpointer=None):
    g = StateGraph(AgentState)
    for name in ("classify", "retrieve", "agent", "tool_node", "synthesize", "grounding_check",
                 "safe_fallback", "finalize"):
        g.add_node(name, getattr(nodes, name))
    g.add_edge(START, "classify")
    g.add_conditional_edges("classify", nodes.after_classify, ["retrieve", "synthesize"])
    g.add_edge("retrieve", "agent")
    g.add_conditional_edges("agent", nodes.after_agent, ["tool_node", "synthesize"])
    g.add_edge("tool_node", "agent")
    g.add_edge("synthesize", "grounding_check")
    g.add_conditional_edges("grounding_check", nodes.after_grounding,
                            ["finalize", "synthesize", "safe_fallback"])
    g.add_edge("safe_fallback", "finalize")
    g.add_edge("finalize", END)
    return g.compile(checkpointer=checkpointer)


def turn_input(message: str, filters: dict | None = None, allow_web: bool = True) -> dict:
    """A turn's input: the new user message (appended to the conversation) and a reset of the working state,
    which would otherwise carry over from the session's checkpoint."""
    return {"messages": [HumanMessage(message)], "plan": None, "contexts": [], "tool_results": [], "steps": 0,
            "model": "", "draft_answer": None, "grounding": None, "retries": 0, "pii_map": {},
            "filters": filters, "allow_web": allow_web, "scratch": [], "flags": [], "answer": None}


def run_config(session_id: str) -> dict:
    return {"configurable": {"thread_id": session_id}, "recursion_limit": RECURSION_LIMIT}


@asynccontextmanager
async def open_checkpointer(path: str | Path):
    """`AsyncSqliteSaver` on data/sessions.db (the async form of §B9.2's `SqliteSaver`, D-021)."""
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    async with aiosqlite.connect(str(path)) as conn:
        saver = AsyncSqliteSaver(conn, serde=JsonPlusSerializer(allowed_msgpack_modules=CHECKPOINT_TYPES))
        await saver.setup()
        yield saver


def mermaid() -> str:
    graph = build_graph(AgentNodes(router=None, retriever=None, models=None, tools=[]))
    return graph.get_graph().draw_mermaid()


def export_mermaid(path: str | Path = "docs/agent_graph.md") -> None:
    Path(path).write_text(
        "# Agent graph\n\nGenerated by `python -m app.agent.graph` from the compiled LangGraph `StateGraph` "
        "(`graph.get_graph().draw_mermaid()`). See capstonespec.md §B9.1 for what each node does.\n\n"
        f"```mermaid\n{mermaid().strip()}\n```\n")


if __name__ == "__main__":
    export_mermaid()
    print("wrote docs/agent_graph.md")
